#!/usr/bin/env bash
# Run:    bash scripts/run_project_training.sh      (detached user service; survives SSH loss)
# Status: cat out/project-train-*/progress.txt ; tail -f out/logs/project-train-*.log
#
# Option A: train whole-project engineering process, then the real-use test.
#   1. SFT on verified project demonstrations (data/project_sft.jsonl) + rehearsal rows
#   2. real-use eval: specs/dnd-music-bot.md through real opencode (trimmed tool config), project
#      folder outside this repo, evidence in out/app-builds/
#   3. one GRPO round in project_env (fresh task seeds)
#   4. real-use eval again
# Judging the evals against specs/dnd-music-bot.criteria.md is done by a person afterwards; the
# evidence (file order, files, independent test rerun, transcript) is collected automatically.
# Pause / resume (e.g. to play a game): bash scripts/train_ctl.sh pause ; bash scripts/train_ctl.sh resume
#   Resuming continues SFT/GRPO from their last resume point and skips finished stages; an interrupted
#   real-use eval runs again (its partial project folder is kept as <app>.interrupted-<time>).
# Do not edit this file while the service runs: bash reads it as it goes.

set -Euo pipefail

ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
PYTHON="$ROOT/.venv-grpo/bin/python"
START_ADAPTER="${START_ADAPTER:-out/until-pass-20261016T024115Z/grpo-2/adapter}"
GRPO_STEPS="${GRPO_STEPS:-12}"
GROUP_SIZE="${GROUP_SIZE:-4}"
REHEARSAL_ROWS="${REHEARSAL_ROWS:-120}"
PROJECT_ROOT="${PROJECT_ROOT:-$HOME/model-apps}"
PORT="${PORT:-8011}"

if [[ "${1:-}" != --worker ]]; then
    [[ "$(loginctl show-user "$USER" -p Linger --value)" == yes ]] \
        || { echo "Error: run 'loginctl enable-linger $USER' first" >&2; exit 1; }
    [[ -s data/project_sft.jsonl ]] || { echo "Error: build data/project_sft.jsonl first" >&2; exit 1; }
    stamp="$(date -u +%Y%m%dT%H%M%SZ)"
    unit="project-train-$stamp"
    source "$ROOT/scripts/launch_lib.sh"
    launch_unit "$unit" "$ROOT/scripts/run_project_training.sh" "STAMP=$stamp" "START_ADAPTER=$START_ADAPTER" \
        "GRPO_STEPS=$GRPO_STEPS" "GROUP_SIZE=$GROUP_SIZE" "REHEARSAL_ROWS=$REHEARSAL_ROWS" \
        "PROJECT_ROOT=$PROJECT_ROOT" "PORT=$PORT" \
        "MEMORY_HIGH=${MEMORY_HIGH:-5500M}" "MEMORY_MAX=${MEMORY_MAX:-6500M}"
    printf 'Service: %s\nLog: %s\nRun: %s\n' "$unit" "$ROOT/out/logs/$unit.log" "$ROOT/out/project-train-$stamp"
    exit 0
fi
RESUME="${RESUME:-0}"

RUN="out/project-train-$STAMP"
mkdir -p "$RUN" out/app-builds "$PROJECT_ROOT"
MODEL="$("$PYTHON" -c "import json; print(json.load(open('out/long-grpo-recovery/base_model.json'))['snapshot'])")"
server_pid=""
trap '[[ -n "$server_pid" ]] && kill "$server_pid" 2>/dev/null' EXIT
log() { echo "$(date -u +%FT%TZ) $*" | tee -a "$RUN/progress.txt"; }

TRAIN=(--model "$MODEL" --env project --critic none --group-size "$GROUP_SIZE" --max-turns 40
       --max-new-tokens 1536 --max-context 12800 --compact-at 9500 --context-schedule 9000
       --lr 2e-6 --sft-lr 5e-6 --temperature 1.0 --token-loop-penalty 0.5 --loop-min-tokens 64
       --eval-episodes 2 --save-every 100 --logit-chunk 32 --qlora --kernels --no-offload --no-activation-offload)

# Real-use eval: the plain spec, once, through real opencode; evidence only, judged by a person.
real_use_eval() {
    local name="$1" adapter="$2" app="dnd-music-bot-$1-$STAMP"
    if [[ -e "$RUN/eval-$name.done" ]]; then
        log "real-use eval $name already done"
        return
    fi
    if [[ -e "$PROJECT_ROOT/$app" ]]; then  # left by a paused run; the build needs a fresh folder
        mv "$PROJECT_ROOT/$app" "$PROJECT_ROOT/$app.interrupted-$(date -u +%Y%m%dT%H%M%SZ)"
    fi
    "$PYTHON" -u -m cutrain.serving.serve_adapter --model "$MODEL" --adapter "$adapter" --name cu-app --port "$PORT" \
        --max-context 20480 --max-new-tokens 2048 --log "out/app-builds/$app.serve.jsonl" \
        > "out/app-builds/$app.server.log" 2>&1 &
    server_pid=$!
    for _ in $(seq 1 90); do
        grep -q '^serving ' "out/app-builds/$app.server.log" && break
        kill -0 "$server_pid" 2>/dev/null || break
        sleep 10
    done
    if grep -q '^serving ' "out/app-builds/$app.server.log"; then
        "$PYTHON" -u -m cutrain.evaluation.build_app_with_opencode --base-url "http://127.0.0.1:$PORT/v1" --model cu-app \
            --spec specs/dnd-music-bot.md --project "$PROJECT_ROOT/$app" --log "out/app-builds/$app.build.json" \
            > "$RUN/eval-$name.txt" 2>&1 || true
        log "real-use eval $name: $(grep -c . "out/app-builds/$app.serve.jsonl" 2>/dev/null || echo 0) model turns; project $PROJECT_ROOT/$app; evidence out/app-builds/$app.build.json"
    else
        log "real-use eval $name: server did not start"
    fi
    kill "$server_pid" 2>/dev/null
    wait "$server_pid" 2>/dev/null
    server_pid=""
    touch "$RUN/eval-$name.done"
}

"$PYTHON" - "$REHEARSAL_ROWS" "$RUN/rehearsal_sft.jsonl" <<'REHEARSAL'
import json
import random
import sys

n = int(sys.argv[1]) // 2
rng = random.Random(0)
general = [l for l in open("out/full-cu-20261015T002706Z/mixed_sft.jsonl") if l.strip()]
opencode = [l for l in open("data/opencode_sft.jsonl") if l.strip()]
rng.shuffle(general)
rng.shuffle(opencode)
open(sys.argv[2], "w").writelines(general[:n] + opencode[:n])
REHEARSAL
SFT_STEPS=$(( $(wc -l < data/project_sft.jsonl) + REHEARSAL_ROWS ))
# A resumed run records the code it continues with, beside the original checksums.
sums="$RUN/SHA256SUMS"
if [[ "$RESUME" == 1 ]]; then
    sums="$RUN/SHA256SUMS.resumed-$(date -u +%Y%m%dT%H%M%SZ)"
    log "resumed"
fi
sha256sum data/project_sft.jsonl cutrain/envs/project_env.py cutrain/envs/project_tasks.py cutrain/envs/project_grader.py cutrain/training/train_long_grpo.py \
    cutrain/serving/serve_adapter.py cutrain/evaluation/build_app_with_opencode.py specs/dnd-music-bot.md > "$sums"

if [[ -d "$RUN/sft/adapter" ]]; then
    log "SFT already done: $RUN/sft/adapter"
else
    log "SFT: $SFT_STEPS steps from $START_ADAPTER"
    "$PYTHON" -u -m cutrain.training.train_long_grpo "${TRAIN[@]}" --adapter "$START_ADAPTER" --out "$RUN/sft" --resume \
        --sft-data data/project_sft.jsonl "$RUN/rehearsal_sft.jsonl" --sft-warmup-steps "$SFT_STEPS" --steps 0 \
        || { log "SFT failed"; exit 1; }
    log "SFT done: $RUN/sft/adapter"
fi
real_use_eval sft "$RUN/sft/adapter"

if [[ -d "$RUN/grpo/adapter" ]]; then
    log "GRPO already done: $RUN/grpo/adapter"
else
    log "GRPO: $GRPO_STEPS groups from $RUN/sft/adapter"
    "$PYTHON" -u -m cutrain.training.train_long_grpo "${TRAIN[@]}" --adapter "$RUN/sft/adapter" --out "$RUN/grpo" --resume \
        --steps "$GRPO_STEPS" --seed 50000 \
        || { log "GRPO failed"; exit 1; }
    log "GRPO done: $RUN/grpo/adapter"
fi
real_use_eval grpo "$RUN/grpo/adapter"
log "ALL DONE"
