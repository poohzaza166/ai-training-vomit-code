#!/usr/bin/env bash
# Run:    bash scripts/run_mix_grpo.sh      (detached user service; survives SSH loss)
# Status: cat out/mix-grpo-*/progress.txt ; tail -f out/logs/mix-grpo-*.log
#
# GRPO on a mix of DeepSeek-V4 + GLM-5.1 reasoning (teacher-answer reward) and MiMo-V2.6-RL-oss code and
# terminal_bench tasks in their own containers (hidden-test reward). See cutrain/envs/mimo_env.py, cutrain/dataprep/prepare_mix_grpo.py.
#   1. GRPO from START_ADAPTER over data/mix_grpo/train.jsonl, one task per group, checkpoint every 10
#   2. harness eval (harness_eval/) of the result, to compare with the start adapter's score
#
# Pause / resume (e.g. to play a game): bash scripts/train_ctl.sh pause ; bash scripts/train_ctl.sh resume
#   Resuming continues from the last finished GRPO step and skips finished stages. After a reboot or
#   crash: bash scripts/train_ctl.sh resume mix-grpo-<stamp>. MEMORY_HIGH / MEMORY_MAX raise the RAM cap.
# Do not edit this file while the service runs: bash reads it as it goes.

set -Euo pipefail

ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
PYTHON="$ROOT/.venv-grpo/bin/python"
START_ADAPTER="${START_ADAPTER:-out/until-pass-20261016T024115Z/grpo-2/adapter}"
TASKS="${TASKS:-data/mix_grpo}"
GRPO_STEPS="${GRPO_STEPS:-$(wc -l < "$TASKS/train.jsonl" 2>/dev/null || echo 0)}"
MIX_OFFSET="${MIX_OFFSET:-0}"
GROUP_SIZE="${GROUP_SIZE:-4}"
EVAL_EPISODES="${EVAL_EPISODES:-3}"

if [[ "${1:-}" != --worker ]]; then
    [[ "$(loginctl show-user "$USER" -p Linger --value)" == yes ]] \
        || { echo "Error: run 'loginctl enable-linger $USER' first" >&2; exit 1; }
    [[ -s "$TASKS/train.jsonl" && -s "$TASKS/eval.jsonl" ]] \
        || { echo "Error: run python -m cutrain.dataprep.prepare_mix_grpo select/validate/schedule first" >&2; exit 1; }
    stamp="$(date -u +%Y%m%dT%H%M%SZ)"
    unit="mix-grpo-$stamp"
    source "$ROOT/scripts/launch_lib.sh"
    # The RAM cap covers the trainer only: task containers run under dockerd (2 GB each, one at a time).
    launch_unit "$unit" "$ROOT/scripts/run_mix_grpo.sh" "STAMP=$stamp" "START_ADAPTER=$START_ADAPTER" "TASKS=$TASKS" \
        "GRPO_STEPS=$GRPO_STEPS" "MIX_OFFSET=$MIX_OFFSET" "GROUP_SIZE=$GROUP_SIZE" "EVAL_EPISODES=$EVAL_EPISODES" \
        "MEMORY_HIGH=${MEMORY_HIGH:-5500M}" "MEMORY_MAX=${MEMORY_MAX:-6500M}"
    printf 'Service: %s\nLog: %s\nRun: %s\n' "$unit" "$ROOT/out/logs/$unit.log" "$ROOT/out/mix-grpo-$stamp"
    exit 0
fi
RESUME="${RESUME:-0}"

RUN="out/mix-grpo-$STAMP"
mkdir -p "$RUN"
MODEL="$("$PYTHON" -c "import json; print(json.load(open('out/long-grpo-recovery/base_model.json'))['snapshot'])")"
log() { echo "$(date -u +%FT%TZ) $*" | tee -a "$RUN/progress.txt"; }
# Leftover task containers from a killed run would hold memory the next rollout needs.
cleanup() { docker ps -aq --filter name=mimo- | xargs -r docker rm -f > /dev/null 2>&1 || true; }
trap cleanup EXIT
cleanup

# A resumed run records the code it continues with, beside the original checksums.
sums="$RUN/SHA256SUMS"
if [[ "$RESUME" == 1 ]]; then
    sums="$RUN/SHA256SUMS.resumed-$(date -u +%Y%m%dT%H%M%SZ)"
    log "resumed"
fi
sha256sum "$TASKS/train.jsonl" "$TASKS/eval.jsonl" cutrain/envs/mimo_env.py cutrain/dataprep/prepare_mix_grpo.py cutrain/envs/project_env.py \
    cutrain/training/train_long_grpo.py cutrain/serving/serve_adapter.py > "$sums"

if [[ -d "$RUN/grpo/adapter" ]]; then
    log "GRPO already done: $RUN/grpo/adapter"
else
    log "GRPO: $GRPO_STEPS groups (offset $MIX_OFFSET) from $START_ADAPTER"
    "$PYTHON" -u -m cutrain.training.train_long_grpo --model "$MODEL" --adapter "$START_ADAPTER" --out "$RUN/grpo" --resume \
        --env mix --mix-tasks "$TASKS" --mix-offset "$MIX_OFFSET" --critic none --group-size "$GROUP_SIZE" \
        --max-turns 40 --max-new-tokens 1536 --max-context 12800 --compact-at 9500 --context-schedule 9000 \
        --lr 2e-6 --temperature 1.0 --token-loop-penalty 0.5 --loop-min-tokens 64 \
        --eval-episodes "$EVAL_EPISODES" --save-every 10 --logit-chunk 32 --qlora --kernels \
        --no-offload --no-activation-offload --steps "$GRPO_STEPS" --seed 50000 \
        || { log "GRPO failed"; exit 1; }
    log "GRPO done: $RUN/grpo/adapter"
fi

report="out/harness-eval/mix-grpo-$STAMP/report.md"
if [[ -s "$report" ]]; then
    log "harness eval already done: $(grep -h '^\*\*' "$report")"
else
    log "harness eval: $RUN/grpo/adapter"
    harness_eval/run_harness_eval.sh "$RUN/grpo/adapter" "mix-grpo-$STAMP" > "$RUN/harness-eval.txt" 2>&1 \
        && log "harness eval: $(grep -h '^\*\*' "$report")" \
        || log "harness eval failed: $RUN/harness-eval.txt"
fi
log "ALL DONE"
